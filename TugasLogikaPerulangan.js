// - 1 perulangan for

for (let i = 1; i <= 10; i++) {
  console.log('Siswa ke-' + i);
}

// - 1 perulangan while

let pelajaran = ['Matematika', 'Bahasa Indonesia', 'IPA'];
let i = 0;

while (i < pelajaran.length) {
  console.log(pelajaran[i]);
  i++;
}
// - 1 perulangan do while

let nilai = 10;
do {
  console.log('Nilai saya adalah ' + nilai);
} while (nilai < 5);
